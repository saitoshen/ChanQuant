# ------------------------------------------------------------------ 小工具


def _h1(t: str) -> str:
    return f'<h1 style="color:{C_HEAD}; font-size:19pt;">{t}</h1>'


def _h2(t: str) -> str:
    return f'<h2 style="color:{C_HEAD}; font-size:13pt;">{t}</h2>'


def _h3(t: str) -> str:
    return f'<h3 style="color:{C_HEAD}; font-size:11pt;">{t}</h3>'


def _p(t: str, color: str = C_HEAD, size: str = "10pt") -> str:
    return f'<p style="color:{color}; font-size:{size};">{t}</p>'


def _break() -> str:
    return '<p style="page-break-before:always;"></p>'


def _rule() -> str:
    return f'<hr style="border:1px solid {C_LINE};">'


def _table(headers: list[str], rows: list[list[str]],
           widths: list[str] | None = None, aligns: list[str] | None = None) -> str:
    """一张表。`widths` 是百分比 —— Qt 富文本不认百分比列宽，必须换算成像素。"""
    widths = widths or []
    aligns = aligns or []

    def _w(i: int) -> str:
        if i < len(widths):
            try:
                return f' width="{int(CONTENT_PX * float(widths[i].rstrip("%")) / 100)}"'
            except ValueError:
                return ""
        return ""

    out = [f'<table border="1" cellspacing="0" cellpadding="5" width="100%" '
           f'style="border-color:{C_LINE};">']
    out.append("<tr>")
    for i, h in enumerate(headers):
        out.append(f'<th{_w(i)} bgcolor="#eef2f7" align="left">'
                   f'<font color="{C_HEAD}">{h}</font></th>')
    out.append("</tr>")
    for r in rows:
        out.append("<tr>")
        for i, cell in enumerate(r):
            al = "right" if (i < len(aligns) and aligns[i] == "r") else "left"
            out.append(f'<td{_w(i)} align="{al}">{cell}</td>')
        out.append("</tr>")
    out.append("</table>")
    return "".join(out)


def _img(name: str, width: int = CONTENT_PX, cap: str = "") -> str:
    """嵌一张截图。路径必须转成 `file://` URL —— 而且中文文件名要做百分号编码，
    直接拼 `file:///D:/…/策略研究.png` 在 Qt 里是取不到图的。"""
    from PySide6.QtCore import QUrl

    path = os.path.join(IMG_DIR, name)
    url = QUrl.fromLocalFile(path).toString()
    out = f'<p align="center"><img src="{url}" width="{width}"></p>'
    if cap:
        out += _p(cap, C_MUTED, "8.5pt")
    return out


def _note(t: str) -> str:
    """提示块。用左边框 + 灰底，靠 `bgcolor` 撑，别指望 CSS 的 border-left。"""
    return (f'<table cellspacing="0" cellpadding="8" width="100%" bgcolor="#f3f6fb">'
            f'<tr><td><font color="{C_ACC}" size="2">▍</font>'
            f'<font color="{C_HEAD}">{t}</font></td></tr></table>')


def _warn(t: str) -> str:
    return (f'<table cellspacing="0" cellpadding="8" width="100%" bgcolor="#fdf3f3">'
            f'<tr><td><font color="{C_BAD}" size="2">▍</font>'
            f'<font color="{C_HEAD}">{t}</font></td></tr></table>')


def _steps(items: list[str]) -> str:
    """编号步骤。Qt 认 `<ol>` 但缩进难看，手工写序号更稳。"""
    rows = [f'<tr><td width="34" align="right" valign="top">'
            f'<font color="{C_ACC}"><b>{i}</b></font></td>'
            f'<td><font color="{C_HEAD}">{t}</font></td></tr>'
            for i, t in enumerate(items, 1)]
    return ('<table cellspacing="0" cellpadding="3" width="100%">'
            + "".join(rows) + "</table>")



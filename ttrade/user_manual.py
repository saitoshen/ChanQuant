def write_pdf(path: str, title: str = "ChanQuant 使用说明") -> str:
    """渲染并写盘，返回路径。必须在有 QGuiApplication 的进程里调用。"""
    from PySide6.QtCore import QMarginsF, QSizeF, QUrl
    from PySide6.QtGui import QPageLayout, QPageSize, QPdfWriter, QTextDocument
    from PySide6.QtWidgets import QApplication

    if QApplication.instance() is None:
        raise RuntimeError("write_pdf 需要在有 QApplication 的进程里调用")

    os.makedirs(os.path.dirname(os.path.abspath(path)) or ".", exist_ok=True)
    w = QPdfWriter(path)
    w.setPageSize(QPageSize(QPageSize.A4))
    w.setResolution(144)
    w.setPageMargins(QMarginsF(16, 14, 16, 14), QPageLayout.Millimeter)
    w.setTitle(title)
    w.setCreator("ChanQuant")

    doc = QTextDocument()
    # 图片走绝对路径，baseUrl 指向 docs/ 让相对路径也能兜住
    doc.setBaseUrl(QUrl.fromLocalFile(os.path.join(ROOT, "docs") + os.sep))
    doc.setHtml(build_html())
    # 页面尺寸按**设备像素**给：QPdfWriter 的 width/height 已经算上 DPI 与页边距
    doc.setPageSize(QSizeF(w.width(), w.height()))
    doc.print_(w)
    return path
